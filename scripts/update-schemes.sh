#!/bin/sh
# Regenerate crates/rail/src/tui/theme/schemes.txt from the iTerm2-Color-Schemes collection
# (MIT, https://github.com/mbadolato/iTerm2-Color-Schemes), pinned to PIN. Needs git and awk.
# Usage: scripts/update-schemes.sh [SOURCE_DIR]   (SOURCE_DIR: a checkout's ghostty/ directory,
# for tests; the collection is cloned when it is absent.)
set -eu

PIN=c02052159ff9a1c438ff419b7451cd33f9ab4934
OUT="$(dirname "$0")/../crates/rail/src/tui/theme/schemes.txt"

if [ "$#" -ge 1 ]; then
    SRC="$1"
else
    WORK="$(mktemp -d)"
    trap 'rm -rf "$WORK"' EXIT
    git clone -q --depth 1 --filter=blob:none --sparse \
        https://github.com/mbadolato/iTerm2-Color-Schemes "$WORK/repo"
    git -C "$WORK/repo" fetch -q --depth 1 origin "$PIN"
    git -C "$WORK/repo" checkout -q "$PIN"
    git -C "$WORK/repo" sparse-checkout set --no-cone ghostty
    git -C "$WORK/repo" checkout -q "$PIN" -- ghostty
    SRC="$WORK/repo/ghostty"
fi

TMP="$OUT.tmp"
BODY="$OUT.body"
: > "$BODY"
for f in "$SRC"/*; do
    name="$(basename "$f")"
    # One line: name, background, foreground, selection bg, selection fg, palette 0..15.
    awk -v name="$name" -v file="$f" '
        function hex(v) { return v ~ /^#[0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F][0-9a-fA-F]$/ }
        function bad(what) { printf "update-schemes: %s: %s\n", file, what > "/dev/stderr"; failed = 1; exit 1 }
        {
            sub(/\r$/, "")
            if ($0 ~ /^[ \t]*$/ || $0 ~ /^#/) next
            eq = index($0, "=")
            if (eq == 0) next
            key = substr($0, 1, eq - 1); val = substr($0, eq + 1)
            gsub(/^[ \t]+|[ \t]+$/, "", key); gsub(/^[ \t]+|[ \t]+$/, "", val)
            if (key == "palette") {
                split(val, pv, /=/); idx = pv[1] + 0; col = pv[2]
                if (pv[1] !~ /^[0-9]+$/ || idx > 15 || !hex(col)) bad("bad palette line: " $0)
                pal[idx] = col; seen++
            } else if (key == "background" || key == "foreground" || key == "selection-background" || key == "selection-foreground") {
                if (!hex(val)) bad("bad value for " key ": " val)
                v[key] = val
            }
        }
        END {
            if (failed) exit 1
            if (seen != 16) bad("expected 16 palette lines, found " seen)
            for (i = 0; i < 16; i++) if (!(i in pal)) bad("missing palette " i)
            n = split("background foreground selection-background selection-foreground", need, " ")
            for (i = 1; i <= n; i++) if (!(need[i] in v)) bad("missing " need[i])
            line = name "\t" v["background"] "\t" v["foreground"] "\t" v["selection-background"] "\t" v["selection-foreground"]
            for (i = 0; i < 16; i++) line = line "\t" pal[i]
            print line
        }' "$f" >> "$BODY" || { rm -f "$BODY" "$TMP"; exit 1; }
done

{
    printf '# generated by scripts/update-schemes.sh from iTerm2-Color-Schemes %s (MIT); do not edit\n' "$PIN"
    # Sort byte-wise on the lowercased name, the order the parser test checks.
    awk -F '\t' '{ print tolower($1) "\t" $0 }' "$BODY" | LC_ALL=C sort -t "$(printf '\t')" -k1,1 | cut -f2-
} > "$TMP"
rm -f "$BODY"
mv "$TMP" "$OUT"
printf 'wrote %s (%s schemes)\n' "$OUT" "$(($(wc -l < "$OUT") - 1))"
